#!/usr/bin/env python3
"""Writes the GTFS-Madrid-Bench mapping in ShExML, an engine that does not
read RML, from the official RML mapping (third_party/gtfs-bench/mappings/
gtfs-csv.rml.ttl), rule by rule:

    workloads/gtfs/gtfs-csv.shexml           ShExML
    workloads/gtfs/shexml-functions.java     its helper functions

    python3 scripts/gtfs_mappings.py         (rdflib needed)

ShExML's JOIN merges two iterators; it is not the referencing object map of RML,
which builds the parent's IRI. Each of the 12 join conditions of the mapping is
written as a *reference condition* (de Vleeschauwer et al., KGCW 2023):
the object IRI is the parent's subject template filled with the child's join
column. It gives the same graph when every child value has its parent row, as
in GTFS-Madrid-Bench; the harness checks it, as for every engine, against the
reference output at the smallest scale and by triple counts above.

ShExML has no IRI from a full IRI value (a prefix is required) and writes empty
CSV cells as literals: a helper function strips the scheme (the prefix is
http:// or https://, the scheme of the column), and another one tests for an
empty value (IF) in the four columns that have empty cells, so that an empty
cell gives no triple, as in RML. Both are facts of the GTFS-Madrid-Bench data,
the same at every scale (EMPTY, SCHEME below): a guard on every column would be
correct for any data, but ShExML 0.7.1 matches each IF result by a linear search
(RDFGeneratorVisitor, conditionsResultList.find), quadratic in the rows. %DATA% (the data directory) and %MAPPINGS% (this
directory) are filled in by the harness.
"""

import os
import re
import sys

from rdflib import Graph, Namespace, RDF, URIRef

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RML_MAPPING = os.path.join(ROOT, "third_party", "gtfs-bench", "mappings", "gtfs-csv.rml.ttl")
OUT = os.path.join(ROOT, "workloads", "gtfs")
RR = Namespace("http://www.w3.org/ns/r2rml#")
RML = Namespace("http://semweb.mmlab.be/ns/rml#")
XSD = "http://www.w3.org/2001/XMLSchema#"
HEADER = "generated by scripts/gtfs_mappings.py from gtfs-csv.rml.ttl (GTFS-Madrid-Bench): do not edit"


def parse_template(t):
    """'http://x/{a}-{b}' -> ('http://x/', ['a', '-', 'b']) : the constant
    prefix and the rest, columns and separators alternating."""
    i = t.index("{")
    parts = re.split(r"\{([^}]*)\}", t[i:])
    return t[:i], [p for p in parts if p != ""]


def rules(g):
    """The triples maps as plain records: name, file, subject template and
    predicate-object maps (predicate, kind, value, datatype)."""
    out = []
    for tm in sorted(g.subjects(RDF.type, RR.TriplesMap)):
        ls = g.value(tm, RML.logicalSource)
        sm = g.value(tm, RR.subjectMap)
        rec = {"name": str(tm).rsplit("/", 1)[-1], "file": os.path.basename(str(g.value(ls, RML.source))),
               "subject": str(g.value(sm, RR.template)), "poms": []}
        for pom in g.objects(tm, RR.predicateObjectMap):
            pm = g.value(pom, RR.predicateMap)
            p = str(g.value(pm, RR.constant) or g.value(pom, RR.predicate))
            om = g.value(pom, RR.objectMap)
            dt = g.value(om, RR.datatype)
            if g.value(om, RR.constant) is not None:
                rec["poms"].append((p, "constant", str(g.value(om, RR.constant)), None))
            elif g.value(om, RR.template) is not None:
                rec["poms"].append((p, "template", str(g.value(om, RR.template)), None))
            elif g.value(om, RML.reference) is not None:
                iri = g.value(om, RR.termType) == RR.IRI
                rec["poms"].append((p, "iri-reference" if iri else "reference",
                                    str(g.value(om, RML.reference)), str(dt) if dt else None))
            elif g.value(om, RR.parentTriplesMap) is not None:
                jc = g.value(om, RR.joinCondition)
                rec["poms"].append((p, "join", (g.value(om, RR.parentTriplesMap),
                                                str(g.value(jc, RR.child)),
                                                str(g.value(jc, RR.parent))), None))
        out.append(rec)
    by_iri = {URIRef("http://example.com/" + r["name"]): r for r in out}
    for r in out:
        for i, (p, kind, v, dt) in enumerate(r["poms"]):
            if kind == "join":
                parent, child, pcol = v
                # the parent's subject template, its join column replaced by the
                # child's: a reference condition
                ptpl = by_iri[parent]["subject"]
                if "{" + pcol + "}" not in ptpl:
                    sys.exit("join %s: the parent's subject does not use %s" % (r["name"], pcol))
                r["poms"][i] = (p, "template", ptpl.replace("{" + pcol + "}", "{" + child + "}"), None)
    return out


class Prefixes:
    """Prefix names for the namespaces and IRI template prefixes of the mapping."""

    def __init__(self):
        self.ns = {}

    def name(self, iri, hint):
        if iri not in self.ns:
            base = re.sub(r"[^A-Za-z0-9]", "", hint) or "p"
            n, k = base, 1
            while n in self.ns.values():
                k += 1
                n = "%s%d" % (base, k)
            self.ns[iri] = n
        return self.ns[iri]

    def curie(self, iri):
        m = re.match(r"^(.*[#/])([A-Za-z_][A-Za-z0-9_-]*)$", iri)
        ns, local = m.group(1), m.group(2)
        hint = {"http://www.w3.org/1999/02/22-rdf-syntax-ns#": "rdf",
                "http://xmlns.com/foaf/0.1/": "foaf", "http://vocab.gtfs.org/terms#": "gtfs",
                "http://purl.org/dc/terms/": "dct", "http://schema.org/": "schema",
                "http://www.w3.org/2003/01/geo/wgs84_pos#": "geo", INV: "inv"}.get(ns, "ns")
        return "%s:%s" % (self.name(ns, hint), local)


XSD_SHORT = {XSD + t: "xsd:" + t for t in ("boolean", "integer", "double", "date", "string")}
# the columns with empty cells in GTFS-Madrid-Bench (at every scale): their references
# are guarded, so that an empty cell gives no triple
EMPTY = {"STOPS.csv": {"zone_id", "parent_station", "stop_timezone"},
         "STOP_TIMES.csv": {"stop_sequence"}}
# the scheme of the IRI-valued columns (one per column at every scale; http otherwise)
SCHEME = {"agency_fare_url": "https"}
GUARD = "helper.notEmpty"


def shexml(recs, header=HEADER):
    px = Prefixes()
    files = sorted({r["file"] for r in recs})
    cols = {f: set() for f in files}
    for r in recs:
        cols[r["file"]].update(re.findall(r"\{([^}]*)\}", r["subject"]))
        if r.get("subject_kind") == "iri-reference":
            cols[r["file"]].add(r["subject"])
        for p, kind, v, dt in r["poms"]:
            if kind in ("reference", "iri-reference"):
                cols[r["file"]].add(v)
            elif kind == "template":
                cols[r["file"]].update(re.findall(r"\{([^}]*)\}", v))
    src = {f: re.sub(r"[^a-z0-9]", "_", f.lower().replace(".csv", "")) for f in files}
    lines, exprs, shapes = [], [], []
    for f in files:
        s = src[f]
        lines.append("SOURCE %s_csv <file://%%DATA%%/%s>" % (s, f))
    lines.append("FUNCTIONS helper <java: file://%MAPPINGS%/shexml-functions.java>")
    for f in files:
        s = src[f]
        lines.append("ITERATOR %s_it <csvperrow> {" % s)
        for c in sorted(cols[f]):
            lines.append("    FIELD %s <%s>" % (c, c))
        lines.append("}")
        exprs.append("EXPRESSION %s <%s_csv.%s_it>" % (s, s, s))
    nkey = [0]

    def term(rec, tpl, guard):
        """prefix:[...] for an IRI template of the record's row."""
        s = src[rec["file"]]
        prefix, parts = parse_template(tpl)
        pname = px.name(prefix, prefix.rstrip("/").rsplit("/", 1)[-1])
        refs = [p for k, p in enumerate(parts) if k % 2 == 0]
        if len(parts) == 1:
            value = "%s.%s" % (s, parts[0])
        else:
            nkey[0] += 1
            key = "key%d" % nkey[0]
            exprs.append("EXPRESSION %s <%s>" % (key, " + ".join(
                ("%s_csv.%s_it.%s" % (s, s, p)) if k % 2 == 0 else '"%s"' % p
                for k, p in enumerate(parts))))
            value = key
        # a single-column template is guarded (an empty cell, no triple); the columns
        # of the multi-column ones (subject keys) are never empty in GTFS-Madrid-Bench
        cond = (" IF %s(%s)" % (GUARD, value)) if guard and len(refs) == 1 and \
            refs[0] in EMPTY.get(rec["file"], ()) else ""
        return "%s:[%s%s]" % (pname, value, cond)

    for r in recs:
        s = src[r["file"]]
        body = []
        for p, kind, v, dt in r["poms"]:
            pred = "a" if p == str(RDF.type) else px.curie(p)
            if kind == "constant":
                body.append("    %s %s ;" % (pred, px.curie(v)))
            elif kind == "template":
                body.append("    %s %s ;" % (pred, term(r, v, True)))
            elif kind == "reference":
                d = (" " + XSD_SHORT[dt]) if dt else ""
                cond = (" IF %s(%s.%s)" % (GUARD, s, v)) if v in EMPTY.get(r["file"], ()) else ""
                body.append("    %s [%s.%s%s]%s ;" % (pred, s, v, cond, d))
            elif kind == "iri-reference":
                scheme = SCHEME.get(v, "http")
                pn = px.name(scheme + "://", "scheme" + scheme)
                body.append("    %s %s:[helper.%sRest(%s.%s)] ;" % (pred, pn, scheme, s, v))
        if r.get("subject_kind") == "iri-reference":
            # an inverted branch (gtfs-inverted): the subject is an IRI-valued column
            scheme = SCHEME.get(r["subject"], "http")
            subj = "%s:[helper.%sRest(%s.%s)]" % (px.name(scheme + "://", "scheme" + scheme),
                                                  scheme, s, r["subject"])
        else:
            # an inverted branch's subject may be an empty cell: guarded
            subj = term(r, r["subject"], "subject_kind" in r)
        shapes.append(":%s %s {\n%s\n}" % (r["name"], subj, "\n".join(body)))
    head = ["# " + header, "PREFIX : <http://example.com/ns#>",
            "PREFIX xsd: <http://www.w3.org/2001/XMLSchema#>"]
    head += ["PREFIX %s: <%s>" % (n, iri) for iri, n in sorted(px.ns.items(), key=lambda x: x[1])]
    return "\n".join(head + lines + exprs) + "\n\n" + "\n".join(shapes) + "\n"


JAVA = """// %s
// Helper functions of the ShExML GTFS mapping (gtfs-csv.shexml).
public class Helper {

    public boolean notEmpty(String value) {
        return value != null && !value.isEmpty();
    }

    public String httpRest(String value) {
        return value.substring("http://".length());
    }

    public String httpsRest(String value) {
        return value.substring("https://".length());
    }
}
""" % HEADER


