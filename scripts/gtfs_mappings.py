# gtfs-inverted: the GTFS-Madrid-Bench mapping with its IRI-valued branches inverted.
#
# Every triple ?s p ?o of the GTFS output whose object ?o is an IRI built from the
# data (an IRI template, an IRI-valued reference, a join: 23 object maps) is written
# ?o inv:p ?s, where inv:p is <http://transport.linkeddata.es/inverse/LOCAL>, LOCAL
# the local name of p. The literal-valued triples and the rdf:type triples stay as
# they are, in the triples map of their entity. In RML a triples map has one subject
# map: each inverted branch needs a triples map of its own (its subject map is the
# object map of the branch); a join is inverted with its direction (the triples map
# reads the parent's source, its subject map is the parent's, and its referencing
# object map points to the child's triples map, the join condition swapped). The
# output has as many distinct triples as GTFS's: the inversion is a bijection.

INV = "http://transport.linkeddata.es/inverse/"
INVERTED_DIR = os.path.join(ROOT, "workloads", "gtfs-inverted")
INVERTED_HEADER = ("generated by scripts/gtfs_mappings.py from gtfs-csv.rml.ttl "
                   "(GTFS-Madrid-Bench): do not edit")


def inverse(p):
    """The inverse predicate of p: INV + its local name."""
    return URIRef(INV + re.split(r"[#/]", str(p))[-1])


def _iri_valued(g, om):
    """'join', 'template', 'reference' (IRI-valued object maps), or None."""
    if g.value(om, RR.parentTriplesMap) is not None:
        return "join"
    if g.value(om, RR.termType) == RR.IRI:
        return "template" if g.value(om, RR.template) is not None else "reference"
    return None


def _predicate(g, pom):
    pm = g.value(pom, RR.predicateMap)
    return g.value(pm, RR.constant) if pm is not None else g.value(pom, RR.predicate)


def _om(g, om):
    """An object map as a plain record: (kind, value, datatype or join)."""
    if g.value(om, RR.parentTriplesMap) is not None:
        return ("join", str(g.value(om, RR.parentTriplesMap)),
                [(str(g.value(j, RR.child)), str(g.value(j, RR.parent)))
                 for j in g.objects(om, RR.joinCondition)])
    if g.value(om, RR.constant) is not None:
        return ("constant", str(g.value(om, RR.constant)), None)
    if g.value(om, RR.template) is not None:
        return ("template" if g.value(om, RR.termType) == RR.IRI else "literal-template",
                str(g.value(om, RR.template)), None)
    dt = g.value(om, RR.datatype)
    return ("iri-reference" if g.value(om, RR.termType) == RR.IRI else "reference",
            str(g.value(om, RML.reference)), str(dt) if dt else None)


def invert_rml(g):
    """(triples maps, number of inverted branches): the gtfs-inverted RML mapping, from
    the GTFS one, as records {name, source, subject: (kind, value), poms: [(predicate,
    object map record)]}, in the order of the GTFS mapping."""
    tms = sorted(g.subjects(RDF.type, RR.TriplesMap))
    sources = {str(tm): str(g.value(g.value(tm, RML.logicalSource), RML.source)) for tm in tms}
    subjects = {str(tm): str(g.value(g.value(tm, RR.subjectMap), RR.template)) for tm in tms}
    out, inv = [], []
    for tm in tms:
        rec = {"name": str(tm), "source": sources[str(tm)],
               "subject": ("template", subjects[str(tm)]), "poms": []}
        for pom in g.objects(tm, RR.predicateObjectMap):
            pred = str(_predicate(g, pom))
            for om in g.objects(pom, RR.objectMap):
                o = _om(g, om)
                (inv if o[0] in ("join", "template", "iri-reference") else rec["poms"]).append(
                    (str(tm), pred, o) if o[0] in ("join", "template", "iri-reference") else (pred, o))
        out.append(rec)
    names = set()
    for tm, pred, (kind, v, extra) in inv:
        p = str(inverse(pred))
        name = "%s_inv_%s" % (tm, p[len(INV):])
        if kind == "join":
            # the parent's source and subject; the child's triples map as the parent,
            # the join condition swapped
            name += "_" + v.rsplit("/", 1)[-1]
            rec = {"name": name, "source": sources[v], "subject": ("template", subjects[v]),
                   "poms": [(p, ("join", tm, [(c2, c1) for c1, c2 in extra]))]}
        else:
            # the branch's object map as the subject map; the entity as the object
            rec = {"name": name, "source": sources[tm],
                   "subject": ("template" if kind == "template" else "iri-reference", v),
                   "poms": [(p, ("template", subjects[tm], None))]}
        if name in names:
            sys.exit("two inverted branches named %s" % name)
        names.add(name)
        out.append(rec)
    preds = {}
    for tm, pred, o in inv:
        preds.setdefault(str(inverse(pred)), set()).add(pred)
    clash = {k: v for k, v in preds.items() if len(v) > 1}
    if clash:
        sys.exit("inverse predicates clash: %s" % clash)
    return out, len(inv)


TTL_PREFIXES = [("rr", "http://www.w3.org/ns/r2rml#"), ("rml", "http://semweb.mmlab.be/ns/rml#"),
                ("ql", "http://semweb.mmlab.be/ns/ql#"),
                ("rdf", "http://www.w3.org/1999/02/22-rdf-syntax-ns#"), ("xsd", XSD),
                ("gtfs", "http://vocab.gtfs.org/terms#"), ("foaf", "http://xmlns.com/foaf/0.1/"),
                ("dct", "http://purl.org/dc/terms/"), ("geo", "http://www.w3.org/2003/01/geo/wgs84_pos#"),
                ("schema", "http://schema.org/"), ("inv", INV)]


def turtle(recs, header):
    """The triples maps of invert_rml() in Turtle, one block per triples map."""
    def iri(x):
        for pfx, ns in TTL_PREFIXES:
            if x.startswith(ns) and re.match(r"^[A-Za-z_][A-Za-z0-9_-]*$", x[len(ns):]):
                return "%s:%s" % (pfx, x[len(ns):])
        return "<%s>" % x

    def lit(x):
        return '"%s"' % x.replace("\\", "\\\\").replace('"', '\\"')

    def om(o):
        kind, v, extra = o
        if kind == "constant":
            return "rr:constant %s" % iri(v)
        if kind == "template":
            return "rr:template %s; rr:termType rr:IRI" % lit(v)
        if kind == "literal-template":
            return "rr:template %s" % lit(v)
        if kind == "iri-reference":
            return "rml:reference %s; rr:termType rr:IRI" % lit(v)
        if kind == "reference":
            return "rml:reference %s%s" % (lit(v), "; rr:datatype %s" % iri(extra) if extra else "")
        return "rr:parentTriplesMap %s;\n            %s" % (iri(v), ";\n            ".join(
            "rr:joinCondition [ rr:child %s; rr:parent %s ]" % (lit(c), lit(q)) for c, q in extra))
    lines = ["# " + header] + ["@prefix %s: <%s> ." % x for x in TTL_PREFIXES] + [""]
    for r in recs:
        kind, v = r["subject"]
        sm = ("rr:template %s" if kind == "template" else "rml:reference %s; rr:termType rr:IRI") % lit(v)
        block = ["%s a rr:TriplesMap;" % iri(r["name"]),
                 "    rml:logicalSource [ rml:source %s; rml:referenceFormulation ql:CSV ];" % lit(r["source"]),
                 "    rr:subjectMap [ %s ]" % sm]
        for p, o in r["poms"]:
            block[-1] += ";"
            block.append("    rr:predicateObjectMap [ rr:predicate %s;\n        rr:objectMap [ %s ] ]"
                         % (iri(p), om(o)))
        block[-1] += " ."
        lines += block + [""]
    return "\n".join(lines)


def inverted_rules(recs):
    """The records of rules() (joins as reference conditions) for ShExML: the
    IRI-valued branches out of their entity's shape, each in a shape of its own
    whose subject is the branch's IRI and whose object is the entity."""
    out = []
    for r in recs:
        keep = [x for x in r["poms"] if x[1] not in ("template", "iri-reference")]
        out.append(dict(r, poms=keep))
    for r in recs:
        n = {}
        for p, kind, v, dt in r["poms"]:
            if kind not in ("template", "iri-reference"):
                continue
            local = str(inverse(p))[len(INV):]
            n[local] = n.get(local, 0) + 1
            name = "%s_inv_%s%s" % (r["name"], local, "" if n[local] == 1 else "_%d" % n[local])
            out.append({"name": name, "file": r["file"], "subject": v,
                        "subject_kind": kind, "poms": [(str(inverse(p)), "template",
                                                        r["subject"], None)]})
    return out


def invert_sa(text, inverted):
    """The gtfs-inverted SPARQL Anything query from the GTFS one: in its CONSTRUCT
    template, every triple whose predicate is in `inverted` (prefixed names) is
    written object inv:p subject; the WHERE clause is the same."""
    head, rest = text.split("CONSTRUCT {", 1)
    tpl, where = rest.split("\n}\nWHERE {", 1)
    keep, inv = [], []
    for block in re.split(r"\s\.\s*\n", tpl.strip().rstrip(".").strip()):
        block = " ".join(block.split())
        s, body = block.split(" ", 1)
        pos = []
        for po in body.split(" ; "):
            p, objs = po.strip().split(" ", 1)
            objs = [o.strip() for o in objs.split(",")]
            if p in inverted:
                inv.extend("  %s inv:%s %s ." % (o, p.split(":", 1)[1], s) for o in objs)
            else:
                pos.append("%s %s" % (p, ", ".join(objs)))
        if pos:
            keep.append("  %s %s ." % (s, " ; ".join(pos)))
    head = head.replace("counterpart of the official mapping mappings/gtfs-csv.rml.ttl",
                        "counterpart of gtfs-inverted-csv.rml.ttl (the GTFS mapping, its\n"
                        "# IRI-valued branches inverted)")
    head = "# " + INVERTED_HEADER + "\n" + head.replace(
        "PREFIX xyz:", "PREFIX inv:    <%s>\nPREFIX xyz:" % INV, 1)
    return head + "CONSTRUCT {\n" + "\n".join(keep) + "\n  # the inverted branches\n" + \
        "\n".join(inv) + "\n}\nWHERE {" + where


def write_inverted(g):
    """Writes workloads/gtfs-inverted/: the RML mapping, the ShExML mapping and its
    helper functions, the SPARQL Anything query. Returns the counts."""
    os.makedirs(INVERTED_DIR, exist_ok=True)
    recs, nbranches = invert_rml(g)
    ntms = len(recs)
    with open(os.path.join(INVERTED_DIR, "gtfs-inverted-csv.rml.ttl"), "w", encoding="utf-8") as f:
        f.write(turtle(recs, "%s\n# %d triples maps: the 13 of GTFS, and one per inverted branch (%d)"
                       % (INVERTED_HEADER, ntms, nbranches)))
    recs = inverted_rules(rules(g))
    with open(os.path.join(INVERTED_DIR, "gtfs-inverted-csv.shexml"), "w", encoding="utf-8") as f:
        f.write(shexml(recs, INVERTED_HEADER))
    with open(os.path.join(INVERTED_DIR, "shexml-functions.java"), "w", encoding="utf-8") as f:
        f.write(JAVA)
    sa = open(os.path.join(OUT, "gtfs-csv.sa.sparql"), encoding="utf-8").read()
    px = Prefixes()
    inverted = set()
    for tm in g.subjects(RDF.type, RR.TriplesMap):
        for pom in g.objects(tm, RR.predicateObjectMap):
            for om in g.objects(pom, RR.objectMap):
                if _iri_valued(g, om):
                    inverted.add(px.curie(str(_predicate(g, pom))))
    with open(os.path.join(INVERTED_DIR, "gtfs-inverted-csv.sa.sparql"), "w", encoding="utf-8") as f:
        f.write(invert_sa(sa, inverted))
    return ntms, nbranches


def main():
    g = Graph()
    g.parse(RML_MAPPING, format="turtle")
    recs = rules(g)
    with open(os.path.join(OUT, "gtfs-csv.shexml"), "w", encoding="utf-8") as f:
        f.write(shexml(recs))
    with open(os.path.join(OUT, "shexml-functions.java"), "w", encoding="utf-8") as f:
        f.write(JAVA)
    print("written: workloads/gtfs/gtfs-csv.shexml, shexml-functions.java")
    ntms, nb = write_inverted(g)
    print("written: workloads/gtfs-inverted/ (%d triples maps, %d inverted branches)" % (ntms, nb))


if __name__ == "__main__":
    main()
